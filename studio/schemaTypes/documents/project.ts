import {defineArrayMember, defineField, defineType} from 'sanity'

export const projectType = defineType({
  name: 'project',
  title: 'Project',
  type: 'document',
  initialValue: {
    status: 'ongoing',
    featured: false,
    portfolioVisible: true,
    showClientOnWebsite: false,
    location: {
      _type: 'location',
      city: 'New York',
      state: 'NY',
      showStreetAddress: false,
    },
    sizeUnit: 'sq-ft',
    overviewHeading: 'Project Overview',
    challengeHeading: 'The Challenge',
    solutionHeading: 'The JCCM Solution',
    resultsHeading: 'Results & Value Delivered',
    seo: {
      _type: 'seo',
      noIndex: false,
    },
  },
  groups: [
    {name: 'basic', title: 'Basic information', default: true},
    {name: 'summary', title: 'Executive summary'},
    {name: 'caseStudy', title: 'Case study'},
    {name: 'media', title: 'Media'},
    {name: 'seo', title: 'SEO'},
    {name: 'settings', title: 'Settings'},
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'Project title',
      type: 'string',
      group: 'basic',
      validation: (Rule) => Rule.required().max(120),
    }),
    defineField({
      name: 'internalProjectNumber',
      title: 'Internal project number',
      type: 'string',
      group: 'basic',
      validation: (Rule) => Rule.max(80),
    }),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      group: 'basic',
      options: {source: 'title', maxLength: 96},
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'status',
      title: 'Project status',
      type: 'string',
      group: 'basic',
      options: {
        layout: 'radio',
        list: [
          {title: 'Ongoing', value: 'ongoing'},
          {title: 'Completed', value: 'completed'},
          {title: 'On hold', value: 'on-hold'},
          {title: 'Upcoming', value: 'upcoming'},
        ],
      },
      initialValue: 'ongoing',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'publishedAt',
      title: 'Original publication date',
      type: 'datetime',
      group: 'basic',
    }),
    defineField({
      name: 'primaryCategory',
      title: 'Primary category',
      type: 'reference',
      group: 'basic',
      to: [{type: 'category'}],
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'additionalCategories',
      title: 'Additional categories',
      type: 'array',
      group: 'basic',
      of: [defineArrayMember({type: 'reference', to: [{type: 'category'}]})],
      validation: (Rule) => Rule.unique(),
    }),
    defineField({
      name: 'projectType',
      title: 'Project type',
      type: 'string',
      group: 'basic',
      description: 'A precise description, such as Mixed-Use Residential.',
      validation: (Rule) => Rule.required().max(120),
    }),
    defineField({
      name: 'tags',
      title: 'Tags',
      type: 'array',
      group: 'basic',
      of: [defineArrayMember({type: 'string'})],
      options: {layout: 'tags'},
      validation: (Rule) => Rule.unique(),
    }),
    defineField({
      name: 'featured',
      title: 'Featured project',
      type: 'boolean',
      group: 'settings',
      initialValue: false,
    }),
    defineField({
      name: 'featuredOrder',
      title: 'Featured order',
      type: 'number',
      group: 'settings',
      hidden: ({parent}) => !parent?.featured,
      validation: (Rule) =>
        Rule.integer()
          .min(0)
          .custom((value, context) => {
            const parent = context.parent as {featured?: boolean} | undefined
            return !parent?.featured || value !== undefined
              ? true
              : 'Featured projects require a display order.'
          }),
    }),
    defineField({
      name: 'portfolioVisible',
      title: 'Visible in portfolio',
      type: 'boolean',
      group: 'settings',
      initialValue: true,
    }),
    defineField({
      name: 'showClientOnWebsite',
      title: 'Show client on website',
      type: 'boolean',
      group: 'summary',
      description:
        'Off displays “Confidential.” Because this dataset is public, only enter a client name approved for public release.',
      initialValue: false,
    }),
    defineField({
      name: 'publicClientName',
      title: 'Public client name',
      type: 'string',
      group: 'summary',
      description: 'Do not enter a confidential identity here.',
      hidden: ({parent}) => !parent?.showClientOnWebsite,
      validation: (Rule) =>
        Rule.max(120).custom((value, context) => {
          const parent = context.parent as {showClientOnWebsite?: boolean} | undefined
          return !parent?.showClientOnWebsite || value
            ? true
            : 'Enter the approved public client name.'
        }),
    }),
    defineField({
      name: 'location',
      title: 'Location',
      type: 'location',
      group: 'summary',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'projectSize',
      title: 'Project size',
      type: 'number',
      group: 'summary',
      validation: (Rule) => Rule.positive(),
    }),
    defineField({
      name: 'sizeUnit',
      title: 'Size unit',
      type: 'string',
      group: 'summary',
      options: {
        list: [
          {title: 'Square feet', value: 'sq-ft'},
          {title: 'Square meters', value: 'sq-m'},
        ],
      },
      initialValue: 'sq-ft',
    }),
    defineField({
      name: 'numberOfUnits',
      title: 'Number of units',
      type: 'number',
      group: 'summary',
      validation: (Rule) => Rule.integer().positive(),
    }),
    defineField({
      name: 'buildingUse',
      title: 'Building use / type',
      type: 'string',
      group: 'summary',
      description: 'Public-facing use, such as Restaurant & Food Service or Residential.',
      validation: (Rule) => Rule.max(120),
    }),
    defineField({
      name: 'completionDate',
      title: 'Completion date',
      type: 'date',
      group: 'summary',
      validation: (Rule) =>
        Rule.custom((value, context) => {
          const parent = context.parent as {status?: string} | undefined
          return parent?.status !== 'completed' || value
            ? true
            : 'Completed projects should have a completion date.'
        }).warning(),
    }),
    defineField({
      name: 'constructionDuration',
      title: 'Construction duration',
      type: 'constructionDuration',
      group: 'summary',
      description: 'Time spent on construction, such as 5 weeks. Leave blank when unknown.',
    }),
    defineField({
      name: 'services',
      title: 'Roles and services',
      type: 'array',
      group: 'summary',
      of: [defineArrayMember({type: 'reference', to: [{type: 'service'}]})],
      validation: (Rule) => Rule.required().min(1).unique(),
    }),
    defineField({
      name: 'shortExcerpt',
      title: 'Portfolio card excerpt',
      type: 'text',
      rows: 3,
      group: 'summary',
      validation: (Rule) => Rule.required().max(240),
    }),
    defineField({
      name: 'challengeSummary',
      title: 'Challenge summary',
      type: 'text',
      rows: 4,
      group: 'summary',
      validation: (Rule) => Rule.required().max(500),
    }),
    defineField({
      name: 'solutionSummary',
      title: 'Solution summary',
      type: 'text',
      rows: 4,
      group: 'summary',
      validation: (Rule) => Rule.required().max(500),
    }),
    defineField({
      name: 'resultSummary',
      title: 'Result summary',
      type: 'text',
      rows: 4,
      group: 'summary',
      validation: (Rule) => Rule.required().max(500),
    }),
    defineField({
      name: 'overviewHeading',
      title: 'Overview heading',
      type: 'string',
      group: 'caseStudy',
      initialValue: 'Project Overview',
    }),
    defineField({
      name: 'overview',
      title: 'Project overview',
      type: 'array',
      group: 'caseStudy',
      of: [defineArrayMember({type: 'block'})],
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'challengeHeading',
      title: 'Challenge heading',
      type: 'string',
      group: 'caseStudy',
      initialValue: 'The Challenge',
    }),
    defineField({
      name: 'challengeIntroduction',
      title: 'Challenge introduction',
      type: 'array',
      group: 'caseStudy',
      of: [defineArrayMember({type: 'block'})],
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'challengePoints',
      title: 'Challenge points',
      type: 'array',
      group: 'caseStudy',
      of: [defineArrayMember({type: 'string'})],
    }),
    defineField({
      name: 'challengeSections',
      title: 'Challenge sections',
      type: 'array',
      group: 'caseStudy',
      description: 'Ordered challenge headings and descriptions. Existing challenge points can still be used.',
      of: [defineArrayMember({type: 'caseStudySection'})],
    }),
    defineField({
      name: 'solutionHeading',
      title: 'Solution heading',
      type: 'string',
      group: 'caseStudy',
      initialValue: 'The JCCM Solution',
    }),
    defineField({
      name: 'solutionIntroduction',
      title: 'Solution introduction',
      type: 'array',
      group: 'caseStudy',
      of: [defineArrayMember({type: 'block'})],
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'solutionSections',
      title: 'Solution sections',
      type: 'array',
      group: 'caseStudy',
      description: 'Ordered solution headings and descriptions.',
      of: [defineArrayMember({type: 'caseStudySection'})],
    }),
    defineField({
      name: 'phases',
      title: 'Project phases',
      type: 'array',
      group: 'caseStudy',
      of: [defineArrayMember({type: 'projectPhase'})],
    }),
    defineField({
      name: 'resultsHeading',
      title: 'Results heading',
      type: 'string',
      group: 'caseStudy',
      initialValue: 'Results & Value Delivered',
    }),
    defineField({
      name: 'resultsIntroduction',
      title: 'Results introduction',
      type: 'array',
      group: 'caseStudy',
      of: [defineArrayMember({type: 'block'})],
    }),
    defineField({
      name: 'results',
      title: 'Results',
      type: 'array',
      group: 'caseStudy',
      of: [defineArrayMember({type: 'resultItem'})],
      validation: (Rule) => Rule.required().min(1),
    }),
    defineField({
      name: 'closingStatement',
      title: 'Closing statement',
      type: 'array',
      group: 'caseStudy',
      of: [defineArrayMember({type: 'block'})],
    }),
    defineField({
      name: 'metrics',
      title: 'Project metrics',
      type: 'array',
      group: 'caseStudy',
      of: [defineArrayMember({type: 'projectMetric'})],
    }),
    defineField({
      name: 'partners',
      title: 'Partners',
      type: 'array',
      group: 'caseStudy',
      of: [defineArrayMember({type: 'reference', to: [{type: 'partner'}]})],
      validation: (Rule) => Rule.unique(),
    }),
    defineField({
      name: 'testimonials',
      title: 'Testimonials',
      type: 'array',
      group: 'caseStudy',
      of: [defineArrayMember({type: 'reference', to: [{type: 'testimonial'}]})],
      validation: (Rule) => Rule.unique(),
    }),
    defineField({
      name: 'cardImage',
      title: 'Portfolio card image',
      type: 'projectImage',
      group: 'media',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'heroImage',
      title: 'Main hero image',
      type: 'projectImage',
      group: 'media',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'heroSideImageOne',
      title: 'Side hero image 1',
      type: 'projectImage',
      group: 'media',
      description: 'First supporting image beside the main hero image.',
    }),
    defineField({
      name: 'heroSideImageTwo',
      title: 'Side hero image 2',
      type: 'projectImage',
      group: 'media',
      description: 'Second supporting image beside the main hero image.',
    }),
    defineField({
      name: 'gallery',
      title: 'Gallery',
      type: 'array',
      group: 'media',
      of: [defineArrayMember({type: 'projectImage'})],
    }),
    defineField({
      name: 'beforeImages',
      title: 'Before images',
      type: 'array',
      group: 'media',
      of: [defineArrayMember({type: 'projectImage'})],
    }),
    defineField({
      name: 'afterImages',
      title: 'After images',
      type: 'array',
      group: 'media',
      of: [defineArrayMember({type: 'projectImage'})],
    }),
    defineField({
      name: 'videoUrl',
      title: 'Video URL',
      type: 'url',
      group: 'media',
      validation: (Rule) => Rule.uri({scheme: ['http', 'https']}),
    }),
    defineField({
      name: 'documents',
      title: 'Documents and floorplans',
      type: 'array',
      group: 'media',
      of: [
        defineArrayMember({
          type: 'object',
          name: 'projectDocument',
          fields: [
            defineField({
              name: 'title',
              title: 'Document title',
              type: 'string',
              validation: (Rule) => Rule.required(),
            }),
            defineField({
              name: 'file',
              title: 'File',
              type: 'file',
              validation: (Rule) => Rule.required(),
            }),
          ],
          preview: {select: {title: 'title'}},
        }),
      ],
    }),
    defineField({
      name: 'seo',
      title: 'Search and social',
      type: 'seo',
      group: 'seo',
      validation: (Rule) => Rule.required(),
    }),
  ],
  orderings: [
    {
      title: 'Completion date, newest',
      name: 'completionDateDesc',
      by: [{field: 'completionDate', direction: 'desc'}],
    },
    {title: 'Project title', name: 'titleAsc', by: [{field: 'title', direction: 'asc'}]},
  ],
  preview: {
    select: {
      title: 'title',
      category: 'primaryCategory.title',
      location: 'location.displayLocation',
      status: 'status',
      featured: 'featured',
      media: 'cardImage.image',
    },
    prepare({title, category, location, status, featured, media}) {
      const details = [category, location, status, featured ? 'Featured' : undefined].filter(
        Boolean,
      )
      return {title, subtitle: details.join(' · '), media}
    },
  },
})
